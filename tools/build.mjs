// Assembles the pages from src/ and injects shared partials and the icon sprite.
//   node tools/build.mjs
//
//   src/index.template.html  page shell for the homepage
//   src/home/sNN-name.html   homepage sections, in file-name order
//   src/home/sNN-name.css    → assets/css/home.css
//   src/home/sNN-name.js     → assets/js/home.js (each file isolated in its own scope)
//   src/partials/*.html      header, newsletter and footer, shared by every page
import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import { sprite, icons, standalone } from './icons.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const read = (p) => fs.readFileSync(path.join(root, p), 'utf8');
const write = (p, s) => { fs.mkdirSync(path.dirname(path.join(root, p)), { recursive: true }); fs.writeFileSync(path.join(root, p), s); };

const logo = read('src/partials/logo.svg.html').trim();
const partial = (name, page = {}) => {
  let html = read(`src/partials/${name}.html`).replaceAll('{{logo}}', logo);
  if (page.nav) html = html.replace(`data-nav="${page.nav}"`, `data-nav="${page.nav}" aria-current="page"`);
  return html.trim();
};
const region = (html, name, content) => {
  const re = new RegExp(`<!-- ${name}:start -->[\\s\\S]*?<!-- ${name}:end -->`);
  return re.test(html) ? html.replace(re, `<!-- ${name}:start -->\n${content}\n<!-- ${name}:end -->`) : html;
};
export const injectShared = (html, page = {}) => {
  html = region(html, 'sprite', sprite());
  for (const name of ['header', 'newsletter', 'footer']) html = region(html, name, partial(name, page));
  return html;
};

export const sections = (only) => fs.readdirSync(path.join(root, 'src/home'))
  .filter((f) => /^s\d+.*\.html$/.test(f))
  .map((f) => f.replace(/\.html$/, ''))
  .filter((n) => !only || n === only)
  .sort();

export function assemble(names, { css, js } = {}) {
  const tpl = read('src/index.template.html');
  const body = names.map((n) => `<!-- ${n} -->\n${read(`src/home/${n}.html`).trim()}\n`).join('\n');
  let html = tpl.replace('{{sections}}', body).replace('{{css}}', css).replace('{{js}}', js);
  return injectShared(html);
}
export function bundle(names) {
  const exists = (n, ext) => fs.existsSync(path.join(root, `src/home/${n}.${ext}`));
  const css = `/* VIKURA — página inicial (portal). Generated by tools/build.mjs from src/home/*.css */\n\n` +
    names.filter((n) => exists(n, 'css')).map((n) => `/* ===== ${n} ===== */\n${read(`src/home/${n}.css`).trim()}\n`).join('\n');
  const js = `/* VIKURA — página inicial (portal). Generated by tools/build.mjs from src/home/*.js */\n` +
    names.filter((n) => exists(n, 'js')).map((n) => `\n/* ===== ${n} ===== */\n;(() => {\n${read(`src/home/${n}.js`).trim()}\n})();\n`).join('');
  return { css, js };
}

const isMain = process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url);
if (isMain) {
  const names = sections();
  const { css, js } = bundle(names);
  write('assets/css/home.css', css);
  write('assets/js/home.js', js);
  write('index.html', assemble(names, { css: 'assets/css/home.css', js: 'assets/js/home.js' }));
  console.log('index.html ←', names.length, 'sections');

  const pages = { 'artigo.html': { nav: 'mente' }, 'sistema.html': {} };
  for (const [file, page] of Object.entries(pages)) {
    if (!fs.existsSync(path.join(root, file))) continue;
    write(file, injectShared(read(file), page));
    console.log('shared →', file);
  }
  for (const name of Object.keys(icons)) write(`assets/icons/${name}.svg`, standalone(name));
  console.log('icons →', Object.keys(icons).length, 'files in assets/icons');
}
